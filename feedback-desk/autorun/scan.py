#!/usr/bin/env python3
"""Read-only helper for the unattended queue runner (lift-tracker-feedback-queue.sh).

Two jobs, no dependencies outside the standard library:

  scan.py open-orders
      Print one line per work order (data/briefs/wo-NNNN-*.md) that still has
      unfinished work -- an order counts as open if any item it names is not yet
      `done` or `closed`. An item only reaches a work order once it's been
      pulled out of the backlog (that's what `brief` and status `queued` mean),
      so this only ever wakes Claude for work someone actually queued up.

  scan.py digest
      Scan every item for the `needs-clarification` tag the unattended run adds
      when it stops on something only Alston can decide, and (re)write
      autorun/DIGEST.md -- the human-readable "these are waiting on you" list.
      Exit status is the number of flagged items (0 = none), so the runner can
      decide whether to raise a notification.

The frontmatter dialect here matches the Lift Tracker Feedback Desk server's: values are
whatever `json.loads` makes of them, falling back to the raw string.
"""

import datetime as _dt
import glob
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DESK = os.path.dirname(HERE)
ITEMS_DIR = os.path.join(DESK, "data", "items")
BRIEFS_DIR = os.path.join(DESK, "data", "briefs")
DIGEST_FILE = os.path.join(HERE, "DIGEST.md")
REPO_ROOT = os.path.dirname(DESK)

FLAG_TAG = "needs-clarification"
DONE_STATUSES = {"done", "closed"}


def _md_files(directory):
    return sorted(
        f for f in glob.glob(os.path.join(directory, "*.md"))
        if not os.path.basename(f).startswith(".")
    )


def _parse_frontmatter(path):
    """Return the frontmatter dict for a `---`-fenced markdown file, plus the body."""
    with open(path, "r", encoding="utf-8") as fh:
        text = fh.read()
    m = re.match(r"^---\n(.*?)\n---\n?(.*)$", text, re.S)
    if not m:
        return {}, text
    fm = {}
    for line in m.group(1).splitlines():
        km = re.match(r"^([A-Za-z0-9_-]+):\s?(.*)$", line)
        if not km:
            continue
        key, raw = km.group(1), km.group(2).strip()
        try:
            fm[key] = json.loads(raw) if raw else ""
        except ValueError:
            fm[key] = raw
    return fm, m.group(2)


def _item_by_id(item_id):
    for path in _md_files(ITEMS_DIR):
        base = os.path.basename(path)
        if base.startswith(item_id + "-") or base == item_id + ".md":
            return path
    return None


def _tags(fm):
    t = fm.get("tags", [])
    if isinstance(t, str):
        t = [x.strip() for x in t.split(",") if x.strip()]
    return t or []


def cmd_open_orders():
    any_open = False
    for path in _md_files(BRIEFS_DIR):
        fm, _ = _parse_frontmatter(path)
        wo_id = fm.get("id") or os.path.basename(path).split("-")[0]
        item_ids = fm.get("items", [])
        if isinstance(item_ids, str):
            item_ids = [x.strip().strip('"') for x in item_ids.strip("[]").split(",") if x.strip()]
        pending = done = 0
        for iid in item_ids:
            ipath = _item_by_id(iid)
            if not ipath:
                continue
            ifm, _ = _parse_frontmatter(ipath)
            status = str(ifm.get("status", "")).lower()
            if status in DONE_STATUSES:
                done += 1
            else:
                pending += 1
        if pending:
            any_open = True
            print("%s pending=%d done=%d total=%d" % (wo_id, pending, done, pending + done))
    return 0 if any_open else 0


def cmd_digest():
    flagged = []
    for path in _md_files(ITEMS_DIR):
        fm, body = _parse_frontmatter(path)
        if FLAG_TAG not in _tags(fm):
            continue
        qm = re.search(r"^##\s+Open question\s*\n(.*?)(?=\n##\s|\Z)", body, re.S | re.M)
        question = (qm.group(1).strip() if qm else "(no `## Open question` section found)")
        flagged.append({
            "id": fm.get("id", os.path.basename(path)),
            "title": fm.get("title", ""),
            "app": fm.get("app", ""),
            "status": fm.get("status", ""),
            "brief": fm.get("brief", ""),
            "path": os.path.relpath(path, REPO_ROOT),
            "question": question,
        })

    now = _dt.datetime.now().strftime("%Y-%m-%d %H:%M %Z").strip()
    lines = [
        "# Feedback queue - waiting on Alston",
        "",
        "Generated by `autorun/scan.py digest` on the last unattended run (%s)." % now,
        "Each item below is one the automated overnight run **stopped on** rather than",
        "guessing a design decision or taking an action that needed sign-off. It did every",
        "unblocked part; the question is what's left. Answer it in the item file (or in",
        "chat, then re-run the work order), and the tag clears on the next pass.",
        "",
    ]
    if not flagged:
        lines += ["_Nothing flagged. The queue is not blocked on a design decision._", ""]
    else:
        lines += ["%d item%s flagged:" % (len(flagged), "" if len(flagged) == 1 else "s"), ""]
        for f in flagged:
            lines += [
                "## %s - %s" % (f["id"], f["title"]),
                "",
                "- **app:** %s  |  **status:** %s  |  **work order:** %s" % (
                    f["app"], f["status"] or "(none)", f["brief"] or "(none)"),
                "- **file:** `%s`" % f["path"],
                "",
                "### Open question",
                "",
                f["question"],
                "",
            ]
    with open(DIGEST_FILE, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print("wrote %s (%d flagged)" % (os.path.relpath(DIGEST_FILE, REPO_ROOT), len(flagged)))
    return len(flagged)


def main(argv):
    if len(argv) != 2 or argv[1] not in ("open-orders", "digest"):
        sys.stderr.write(__doc__)
        return 2
    return {"open-orders": cmd_open_orders, "digest": cmd_digest}[argv[1]]()


if __name__ == "__main__":
    sys.exit(main(sys.argv))
